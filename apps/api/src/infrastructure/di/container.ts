  const createModelHandler = (collectionName: string) => ({
    findUnique: async ({ where }: any) => {
      const items = collections[collectionName] || [];
      return items.find(item => {
        return Object.entries(where).every(([key, val]) => item[key] === val);
      }) || null;
    },
    findMany: async (params: any = {}) => {
      let items = [...(collections[collectionName] || [])];
      if (params.where) {
        if (params.where.status) {
          items = items.filter(i => i.status === params.where.status);
        }
        if (params.where.batchId) {
          items = items.filter(i => i.batchId === params.where.batchId);
        }
        if (params.where.ownerId && params.where.ownerType) {
          items = items.filter(i => i.ownerId === params.where.ownerId && i.ownerType === params.where.ownerType);
        }
        if (params.where.isActive !== undefined) {
          items = items.filter(i => i.isActive === params.where.isActive);
        }
        if (params.where.countryIso2Code) {
          items = items.filter(i => i.countryIso2Code === params.where.countryIso2Code);
        }
        if (params.where.region) {
          items = items.filter(i => i.region === params.where.region);
        }
      }
      if (params.skip) {
        items = items.slice(params.skip);
      }
      if (params.take) {
        items = items.slice(0, params.take);
      }
      return items;
    },
    count: async (params: any = {}) => {
      let items = [...(collections[collectionName] || [])];
      if (params.where?.status) {
        items = items.filter(i => i.status === params.where.status);
      }
      return items.length;
    },
    create: async ({ data }: any) => {
      const id = data.id || `mem-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
      const now = new Date();
      const newItem = {
        id,
        createdAt: now,
        updatedAt: now,
        ...data,
      };
      if (!collections[collectionName]) collections[collectionName] = [];
      collections[collectionName].push(newItem);
      return newItem;
    },
    createMany: async ({ data }: any) => {
      if (!collections[collectionName]) collections[collectionName] = [];
      const now = new Date();
      const newItems = (Array.isArray(data) ? data : [data]).map(d => ({
        id: d.id || `mem-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
        createdAt: now,
        updatedAt: now,
        ...d,
      }));
      collections[collectionName].push(...newItems);
      return { count: newItems.length };
    },
    update: async ({ where, data }: any) => {
      const items = collections[collectionName] || [];
      const item = items.find(i => {
        return Object.entries(where).every(([key, val]) => i[key] === val);
      });
      if (!item) throw new Error(`Record not found in ${collectionName}`);
      Object.assign(item, data, { updatedAt: new Date() });
      return item;
    },
    upsert: async ({ where, update, create }: any) => {
      const items = collections[collectionName] || [];
      const item = items.find(i => {
        return Object.entries(where).every(([key, val]) => i[key] === val);
      });
      if (item) {
        Object.assign(item, update, { updatedAt: new Date() });
        return item;
      } else {
        const id = create.id || `mem-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
        const now = new Date();
        const newItem = {
          id,
          createdAt: now,
          updatedAt: now,
          ...create,
        };
        if (!collections[collectionName]) collections[collectionName] = [];
        collections[collectionName].push(newItem);
        return newItem;
      }
    },
  });

