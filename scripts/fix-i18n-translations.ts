function autoTranslateSentence(enText: string): string {
  if (!enText || typeof enText !== 'string') return enText;
  const trimmed = enText.trim();

  if (comprehensiveDict[trimmed]) {
    return comprehensiveDict[trimmed];
  }

  let text = trimmed;
  if (!text.includes(' ') && text.includes('_')) {
    text = text.split('_').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  }

  return text
    .replace(/\bID\b/g, 'معرف')
    .replace(/\bURL\b/g, 'رابط')
    .replace(/\bDate\b/g, 'تاريخ')
    .replace(/\bName\b/g, 'اسم')
    .replace(/\bTitle\b/g, 'عنوان')
    .replace(/\bStatus\b/g, 'حالة')
    .replace(/\bType\b/g, 'نوع')
    .replace(/\bDescription\b/g, 'وصف')
    .replace(/\bReference\b/g, 'مرجع')
    .replace(/\bManage\b/gi, 'إدارة')
    .replace(/\bBrowse\b/gi, 'استكشاف')
    .replace(/\bExplore\b/gi, 'استكشاف')
    .replace(/\bSearch\b/gi, 'البحث في')
    .replace(/\bView\b/gi, 'عرض')
    .replace(/\bAdd\b/gi, 'إضافة')
    .replace(/\bEdit\b/gi, 'تعديل')
    .replace(/\bCreate\b/gi, 'إنشاء')
    .replace(/\bDelete\b/gi, 'حذف')
    .replace(/\bSave\b/gi, 'حفظ')
    .replace(/\bLoad\b/gi, 'تحميل')
    .replace(/\bUpdate\b/gi, 'تحديث')
    .replace(/\bSelect\b/gi, 'تحديد');
}

function processDict(
  enObj: Record<string, string>,
  arObj: Record<string, string>,
  enPath: string,
  arPath: string,
  exportName = 'ar'
) {
  const newEn = { ...enObj, ...missingEnKeys };
  const newAr = { ...arObj };

  for (const [key, enVal] of Object.entries(newEn)) {
    if (typeof enVal !== 'string') continue;

    const currentArVal = newAr[key];

    // Check if key needs Arabic translation
    if (!currentArVal || (!/[\u0600-\u06FF]/.test(currentArVal) && /[a-zA-Z]/.test(currentArVal))) {
      if (comprehensiveDict[key]) {
        newAr[key] = comprehensiveDict[key];
      } else {
        newAr[key] = autoTranslateSentence(enVal);
      }
    }
  }

  // Save EN
  fs.writeFileSync(enPath, `export const en = ${JSON.stringify(newEn, null, 2)};\n`, 'utf8');

  // Save AR
  fs.writeFileSync(arPath, `export const ${exportName} = ${JSON.stringify(newAr, null, 2)};\n`, 'utf8');

  console.log(`Updated ${enPath} and ${arPath}`);
}

